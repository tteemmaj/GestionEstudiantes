    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        try {
        String carnet = textoCarne.getText().trim();
        String nombre = textoNombre.getText().trim();
        String apellido = textoApellido.getText().trim();
        String edadTexto = textoEdad.getText().trim();
        String carrera = textoCarrera.getText().trim();

        if (carnet.isEmpty() || nombre.isEmpty() || apellido.isEmpty() || edadTexto.isEmpty() || carrera.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor complete todos los campos.", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        int edad = Integer.parseInt(edadTexto);

        // Verifica si el estudiante ya existe
        Modelo.Estudiante existente = gestion.buscarEstudiante(carnet);
        if (existente == null) {
            Modelo.Estudiante nuevo = new Modelo.Estudiante(carnet, nombre, apellido, edad, carrera);
            gestion.agregarEstudiante(nuevo);
            javax.swing.JOptionPane.showMessageDialog(this, "Estudiante guardado exitosamente.");
        } else {
            existente.setNombre(nombre);
            existente.setApellido(apellido);
            existente.setEdad(edad);
            existente.setCarrera(carrera);
            javax.swing.JOptionPane.showMessageDialog(this, "Estudiante actualizado exitosamente.");
        }

        cargarDatosTabla();
        limpiarFormulario();

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "La edad debe ser un número entero válido.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

