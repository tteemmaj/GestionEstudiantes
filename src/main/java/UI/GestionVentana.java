    public void cargarDatosTabla() {
        if (gestion == null || tablaRegistrados == null) return;

        DefaultTableModel model = (DefaultTableModel) tablaRegistrados.getModel();
        model.setRowCount(0);

        for (Estudiante e : gestion.getListaEstudiantes()) {
            model.addRow(new Object[]{
                e.getCarnet(),
                e.getNombre(),
                e.getApellido(),
                e.getEdad(),
                e.getCarrera()
            });
        }
    }

    private void limpiarFormulario() {
        textoCarne.setText("");
        textoNombre.setText("");
        textoApellido.setText("");
        textoEdad.setText("");
        textoCarrera.setText("");
        textoBuscarCarne.setText("");
        textoCarne.setEditable(true);
        if (tablaRegistrados != null) tablaRegistrados.clearSelection();
    }
    
    private void ejecutarBusqueda() {
        String carnetBusqueda = textoBuscarCarne.getText().trim();

        if (carnetBusqueda.isEmpty() || carnetBusqueda.equalsIgnoreCase("Buscar carné")) {
            JOptionPane.showMessageDialog(this, "Ingrese un carné para buscar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Estudiante encontrado = gestion.buscarEstudiante(carnetBusqueda);

        if (encontrado != null) {
            // 1. Cargar datos en los campos de texto
            textoCarne.setText(encontrado.getCarnet());
            textoNombre.setText(encontrado.getNombre());
            textoApellido.setText(encontrado.getApellido());
            textoEdad.setText(String.valueOf(encontrado.getEdad()));
            textoCarrera.setText(encontrado.getCarrera());
            textoCarne.setEditable(false);

            // 2. Seleccionar la fila en la tabla
            DefaultTableModel model = (DefaultTableModel) tablaRegistrados.getModel();
            for (int i = 0; i < model.getRowCount(); i++) {
                if (model.getValueAt(i, 0).toString().equalsIgnoreCase(carnetBusqueda)) {
                    tablaRegistrados.setRowSelectionInterval(i, i);
                    tablaRegistrados.scrollRectToVisible(tablaRegistrados.getCellRect(i, 0, true));
                    break;
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Estudiante no encontrado.", "Información", JOptionPane.INFORMATION_MESSAGE);
        }
    }
    
    
