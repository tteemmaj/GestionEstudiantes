    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        String carnetELiminar = "";
    int fila = tablaRegistrados.getSelectedRow();

    if (fila >= 0) {
        carnetELiminar = tablaRegistrados.getValueAt(fila, 0).toString();
    } else {
        carnetELiminar = textoCarne.getText().trim();
    }

    if (carnetELiminar.isEmpty() || carnetELiminar.equalsIgnoreCase("Escribir carné")) {
        JOptionPane.showMessageDialog(this, "Seleccione un registro o ingrese un carné para eliminar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int confirmacion = JOptionPane.showConfirmDialog(
        this, 
        "¿Está seguro de eliminar al estudiante con carné " + carnetELiminar + "?", 
        "Confirmar eliminación", 
        JOptionPane.YES_NO_OPTION
    );

    if (confirmacion == JOptionPane.YES_OPTION) {
        boolean eliminado = gestion.eliminarEstudiante(carnetELiminar);
        if (eliminado) {
            JOptionPane.showMessageDialog(this, "Estudiante eliminado correctamente.");
            cargarDatosTabla();
            limpiarFormulario();
        } else {
            JOptionPane.showMessageDialog(this, "No se encontró el estudiante a eliminar.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
        
    }//GEN-LAST:event_btnEliminarActionPerformed

